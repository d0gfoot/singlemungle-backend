create table grooming_style_presets (
	id bigint generated by default as identity primary key,
	name varchar(100) not null unique,
	description text,
	example_image_url text,
	prompt_description text not null,
	negative_prompt text,
	enabled boolean not null default true,
	created_at timestamp not null
);

create table reviews (
	id bigint generated by default as identity primary key,
	user_id bigint not null,
	place_id bigint not null,
	rating integer not null,
	content text not null,
	grooming_style_name varchar(100),
	created_at timestamp not null,
	updated_at timestamp not null,
	deleted_at timestamp,
	constraint fk_reviews_user_id foreign key (user_id) references users (id),
	constraint fk_reviews_place_id foreign key (place_id) references places (id),
	constraint ck_reviews_rating check (rating between 1 and 5)
);

create table review_images (
	id bigint generated by default as identity primary key,
	review_id bigint not null,
	image_url text not null,
	ai_reference_allowed boolean not null default false,
	created_at timestamp not null,
	deleted_at timestamp,
	constraint fk_review_images_review_id foreign key (review_id) references reviews (id)
);

create index idx_reviews_place_id_created_at on reviews (place_id, created_at desc);
create index idx_reviews_user_id_created_at on reviews (user_id, created_at desc);
create index idx_review_images_review_id on review_images (review_id);

