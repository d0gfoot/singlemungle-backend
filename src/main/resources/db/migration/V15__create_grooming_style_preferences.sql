create table grooming_style_preferences (
	id bigint generated by default as identity primary key,
	user_id bigint not null,
	breed_code varchar(100) not null,
	breed_name varchar(100) not null,
	style_preset_id bigint not null,
	source_simulation_id bigint not null,
	created_at timestamp not null,
	updated_at timestamp not null,
	constraint fk_style_preferences_user_id foreign key (user_id) references users (id),
	constraint fk_style_preferences_preset_id foreign key (style_preset_id) references grooming_style_presets (id),
	constraint fk_style_preferences_simulation_id foreign key (source_simulation_id) references beauty_style_simulations (id),
	constraint uk_style_preferences_user_breed unique (user_id, breed_code)
);

create index idx_style_preferences_breed_preset
	on grooming_style_preferences (breed_code, style_preset_id);
