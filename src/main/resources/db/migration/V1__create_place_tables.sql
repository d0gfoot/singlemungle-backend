create table places (
	id bigint generated by default as identity primary key,
	provider varchar(20) not null,
	external_place_id varchar(100) not null,
	place_type varchar(30) not null,
	name varchar(100) not null,
	address varchar(255),
	road_address varchar(255),
	latitude decimal(10, 7) not null,
	longitude decimal(10, 7) not null,
	phone varchar(30),
	place_url text,
	reservation_url text,
	is_verified boolean not null default false,
	created_at timestamp not null,
	updated_at timestamp not null,
	constraint uk_places_provider_external_place_id unique (provider, external_place_id)
);

create index idx_places_place_type on places (place_type);

create table place_images (
	id bigint generated by default as identity primary key,
	place_id bigint not null,
	image_url text not null,
	sort_order integer not null default 0,
	created_at timestamp not null,
	constraint fk_place_images_place_id foreign key (place_id) references places (id)
);

create table place_business_hours (
	id bigint generated by default as identity primary key,
	place_id bigint not null,
	day_of_week varchar(20) not null,
	open_time time,
	close_time time,
	break_start_time time,
	break_end_time time,
	is_closed boolean not null default false,
	constraint fk_place_business_hours_place_id foreign key (place_id) references places (id),
	constraint uk_place_business_hours_place_id_day_of_week unique (place_id, day_of_week)
);

create table place_services (
	id bigint generated by default as identity primary key,
	place_id bigint not null,
	service_name varchar(100) not null,
	description text,
	created_at timestamp not null,
	updated_at timestamp not null,
	constraint fk_place_services_place_id foreign key (place_id) references places (id)
);
