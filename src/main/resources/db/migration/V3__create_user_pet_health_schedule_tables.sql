create table users (
	id bigint generated by default as identity primary key,
	nickname varchar(50),
	phone varchar(30),
	created_at timestamp,
	updated_at timestamp,
	deleted_at timestamp
);

create table pets (
	id bigint generated by default as identity primary key,
	user_id bigint,
	name varchar(255),
	breed varchar(255),
	gender varchar(255),
	birth_date date,
	weight float(53),
	profile_image_url text,
	memo text,
	is_representative boolean,
	created_at timestamp,
	updated_at timestamp,
	deleted_at timestamp
);

create table pet_health_records (
	id bigint generated by default as identity primary key,
	pet_id bigint,
	record_type varchar(255),
	title varchar(255),
	hospital_name varchar(255),
	record_date date,
	description text,
	next_schedule_date date,
	created_at timestamp,
	updated_at timestamp
);

create table schedules (
	id bigint generated by default as identity primary key,
	user_id bigint,
	pet_id bigint,
	schedule_type varchar(255),
	title varchar(255),
	start_at timestamp,
	end_at timestamp,
	location varchar(255),
	memo text,
	is_alarm boolean,
	created_at timestamp,
	updated_at timestamp
);

create table favorite_places (
	id bigint generated by default as identity primary key,
	user_id bigint,
	place_id bigint,
	memo text,
	created_at timestamp,
	constraint fk_favorite_places_place_id foreign key (place_id) references places (id)
);

create index idx_pets_user_id on pets (user_id);
create index idx_pet_health_records_pet_id on pet_health_records (pet_id);
create index idx_pet_health_records_pet_id_record_type on pet_health_records (pet_id, record_type);
create index idx_schedules_user_id on schedules (user_id);
create index idx_favorite_places_user_id on favorite_places (user_id);
