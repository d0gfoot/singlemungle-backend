create table beauty_style_simulations (
	id bigint generated by default as identity primary key,
	user_id bigint not null,
	pet_id bigint not null,
	shop_id bigint not null,
	style_keyword varchar(100) not null,
	source_image_url text not null,
	style_image_url text,
	generated_image_url text,
	storage_provider varchar(30) not null,
	status varchar(20) not null,
	failure_reason text,
	expires_at timestamp not null,
	created_at timestamp not null,
	deleted_at timestamp,
	constraint fk_beauty_style_simulations_user_id foreign key (user_id) references users (id),
	constraint fk_beauty_style_simulations_pet_id foreign key (pet_id) references pets (id),
	constraint fk_beauty_style_simulations_shop_id foreign key (shop_id) references places (id)
);

create index idx_beauty_style_simulations_user_id_created_at
	on beauty_style_simulations (user_id, created_at desc);

create index idx_beauty_style_simulations_user_id_expires_at
	on beauty_style_simulations (user_id, expires_at);

create index idx_beauty_style_simulations_pet_id
	on beauty_style_simulations (pet_id);
